const {test,expect}=require('@playwright/test');
test('payment link creation, switches, persistence and product isolation',async({page})=>{
 await page.goto('/products.html');
 await page.locator('.product-table tbody tr').first().getByRole('button',{name:'付款連結管理'}).click();
 const modal=page.locator('.payment-links-modal');
 await expect(modal).toBeVisible();await expect(modal).toContainText('暫無資料');
 await modal.getByRole('button',{name:'新增付款連結'}).click();
 await expect(modal.getByRole('alert')).toContainText('請選擇至少一種');
 await modal.getByRole('checkbox',{name:'Line Pay',exact:true}).check();
 await modal.getByRole('textbox',{name:'交易結果返回頁'}).fill('https://example.com/result');
 await modal.getByRole('switch',{name:'是否開立發票'}).click();
 await modal.getByRole('button',{name:'新增付款連結'}).click();
 const row=modal.locator('tbody tr').first();
 await expect(row).toContainText('Line Pay');await expect(row).toContainText('https://example.com/result');
 await expect(row.locator('td').nth(4)).toHaveText('否');
 await expect(row.getByRole('switch')).toHaveAttribute('aria-checked','false');
 await expect(row.locator('.payment-link-url')).toContainText('https://payment.example.com/pay/692/');
 await row.getByRole('switch').click();await expect(row.getByRole('switch')).toHaveAttribute('aria-checked','true');
 await page.screenshot({path:'test-results/payment-links-desktop.png'});
 await modal.getByRole('button',{name:'關閉付款連結管理'}).click();await page.reload();
 await page.locator('.product-table tbody tr').first().getByRole('button',{name:'付款連結管理'}).click();
 await expect(row.getByRole('switch')).toHaveAttribute('aria-checked','true');
 await modal.getByRole('checkbox',{name:'全選',exact:true}).check();
 await expect(modal.locator('.payment-method-options input:checked')).toHaveCount(9);
 await modal.getByRole('button',{name:'新增付款連結'}).click();
 await expect(modal.locator('tbody tr')).toHaveCount(2);
 await expect(modal.locator('tbody tr').last().getByRole('switch')).toHaveAttribute('aria-checked','false');
 await page.keyboard.press('Escape');
 await page.locator('.product-table tbody tr').nth(1).getByRole('button',{name:'付款連結管理'}).click();await expect(modal).toContainText('暫無資料');
 await page.setViewportSize({width:390,height:844});
 const bounds=await modal.boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(390);
 await page.screenshot({path:'test-results/payment-links-mobile.png'});
});
